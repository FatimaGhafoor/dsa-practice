// Print the squares of numbers from 1 to n.

function printSquares(n) {
  for (let i = 1; i <= n; i++) {
    console.log(i * i);
  }
}

printSquares(5);

/* 
Approach: Iterate from 1 to n using a loop and multiply each number by itself to find and print its square.

Time Complexity: O(n);
Space Complexity: O(1);
*/
